import {readFile,writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {resolve} from 'node:path';
import {runtimeZip} from '../release.mjs';
import {outputPath} from '../audit-artifacts.mjs';
const root=fileURLToPath(new URL('./console-web-validation/',import.meta.url));
const files=new Map();
for(const name of ['manifest.json','core.js','probe.js','panel.js'])files.set(name,await readFile(resolve(root,name)));
const path=await outputPath(process.argv[2]??'audit-artifacts/console-web-validation/GL-Console-Web-Validation.zip');
await writeFile(path,runtimeZip(files));console.log('Created read-only validation helper: '+path);
